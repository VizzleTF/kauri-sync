// Command kauri-vectors writes the Kauri Sync v1 test vectors as JSON.
// Clients must reproduce every value from the inputs in the file; the
// envelopes can't be reproduced (ML-KEM encapsulation is randomized), so
// clients must open them instead.
//
//	go run ./cmd/kauri-vectors > ../kauri/docs/sync-vectors/v1.json
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"os"

	"github.com/VizzleTF/kauri-sync/kauri"
)

func h(b []byte) string { return hex.EncodeToString(b) }

func seq(n int, start byte) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

func main() {
	var secret [32]byte
	copy(secret[:], seq(32, 0x00))
	c := kauri.DeriveChain(secret)
	var dk [32]byte
	copy(dk[:], seq(32, 0x40))
	var nonce [24]byte
	copy(nonce[:], seq(24, 0xa0))

	out := map[string]any{
		"_note": "Hex unless the name says b64. Generated by kauri-sync/cmd/kauri-vectors from the reference implementation (Go package kauri).",
	}

	out["chain"] = map[string]any{
		"secret":        h(secret[:]),
		"words":         c.Words(),
		"chain_id":      h(c.ID[:]),
		"chain_id_hash": func() string { s := kauri.IDHash(c.ID[:]); return h(s[:]) }(),
		"chain_key_pub": h(c.AuthPublic()),
		"wrap_key":      h(c.WrapKey[:]),
		"id_key":        h(c.IDKey[:]),
		"name_key":      h(c.NameKey[:]),
	}

	recID := c.RecordID("snippet", "6d2f3c50-0000-4000-8000-000000000001")
	plain := []byte(`{"k":"snippet","f":{"title":["Hello",[1762600000000,0,"AAAAAAAAAAAAAAAAAAAAAA"]]},"d":null}`)
	padded, _ := kauri.Pad(plain)
	body := kauri.SealWithNonce(dk, nonce, padded, c.RecordAAD(recID, 1))
	blobContent := []byte("blob content")
	blobID := c.BlobID(blobContent)
	blobBody := kauri.SealWithNonce(dk, nonce, kauri.Pad64(blobContent), append(append(append([]byte{}, c.ID[:]...), blobID...), 0, 0, 0, 1))
	wrapped := kauri.SealWithNonce(c.WrapKey, nonce, dk[:], append(append([]byte("kauri-sync/v1/keyring"), c.ID[:]...), 0, 0, 0, 1))

	out["record"] = map[string]any{
		"kind":          "snippet",
		"local_uuid":    "6d2f3c50-0000-4000-8000-000000000001",
		"record_id":     h(recID),
		"record_id_b64": kauri.B64.EncodeToString(recID),
		"data_key":      h(dk[:]),
		"epoch":         1,
		"nonce":         h(nonce[:]),
		"plaintext":     string(plain),
		"padded_len":    len(padded),
		"aad":           h(c.RecordAAD(recID, 1)),
		"body":          h(body),
	}
	out["blob"] = map[string]any{
		"content":     string(blobContent),
		"blob_id":     h(blobID),
		"nonce":       h(nonce[:]),
		"epoch":       1,
		"padded_len":  len(kauri.Pad64(blobContent)),
		"body_sha256": func() string { s := sha256.Sum256(blobBody); return h(s[:]) }(),
	}
	out["keyring"] = map[string]any{"epoch": 1, "nonce": h(nonce[:]), "wrapped": h(wrapped)}

	pads := []map[string]any{}
	for _, n := range []int{0, 255, 256, 1023, 1024, 65535} {
		p, _ := kauri.Pad(bytes.Repeat([]byte{'a'}, n))
		pads = append(pads, map[string]any{"plaintext_len": n, "padded_len": len(p)})
	}
	out["padding"] = pads

	dev, _ := kauri.DeviceFromSeeds(seq(32, 0x10), seq(32, 0x30), seq(64, 0x50))
	reqNonce := seq(16, 0xc0)
	reqBody := []byte(`{"records":[]}`)
	sig := dev.SignRequest("POST", "/v1/records", 1762600000, reqNonce, reqBody)
	out["device"] = map[string]any{
		"ed25519_seed":        h(seq(32, 0x10)),
		"x25519_priv":         h(seq(32, 0x30)),
		"mlkem768_seed":       h(seq(64, 0x50)),
		"ed25519_pub":         h(dev.Public()),
		"x25519_pub":          h(dev.Recipient().X25519),
		"mlkem768_pub_sha256": func() string { s := sha256.Sum256(dev.Recipient().MLKEM); return h(s[:]) }(),
		"device_id":           h(dev.ID()),
		"chain_sig":           h(c.AddSignature(dev.Public())),
		"name":                "Ivan's MacBook",
	}
	out["request"] = map[string]any{
		"method":    "POST",
		"path":      "/v1/records",
		"time":      1762600000,
		"nonce":     h(reqNonce),
		"body":      string(reqBody),
		"message":   h(kauri.RequestMessage("POST", "/v1/records", 1762600000, reqNonce, reqBody)),
		"signature": h(sig),
	}

	hybrid, _ := kauri.SealEnvelope(c.ID[:], 1, dev.Recipient(), dk[:])
	old := *dev
	old.MLKEM = nil
	classic, _ := kauri.SealEnvelope(c.ID[:], 1, old.Recipient(), dk[:])
	out["envelopes"] = map[string]any{
		"_note":  "Open these with the device keys above; the payload is record.data_key.",
		"epoch":  1,
		"hybrid": h(hybrid),
		"x25519": h(classic),
	}

	code := "ABCD-EFGH-JKMN"
	norm, _ := kauri.NormalizePairCode(code)
	pa := kauri.NewPairingFromSeed(norm, true, seq(64, 0x01))
	pb := kauri.NewPairingFromSeed(norm, false, seq(64, 0x81))
	ka, _ := pa.Finish(pb.Msg)
	kb, _ := pb.Finish(pa.Msg)
	if !ka.CheckConfirm(kb.ConfirmB) || ka.BoxKey != kb.BoxKey {
		panic("pairing vectors disagree")
	}
	out["pairing"] = map[string]any{
		"code":           code,
		"normalized":     norm,
		"slot":           pa.Slot,
		"x_seed":         h(seq(64, 0x01)),
		"y_seed":         h(seq(64, 0x81)),
		"_note":          "x = seed reduced mod L (64-byte little-endian), likewise y",
		"pA":             h(pa.Msg),
		"pB":             h(pb.Msg),
		"confirm_b":      h(kb.ConfirmB),
		"box_key":        h(kb.BoxKey[:]),
		"number":         kb.Number,
		"approval":       h(kauri.SealWithNonce(kb.BoxKey, nonce, secret[:], []byte("kauri-pair-v1/approve"+pa.Slot))),
		"approval_nonce": h(nonce[:]),
	}

	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	_ = enc.Encode(out)
}
